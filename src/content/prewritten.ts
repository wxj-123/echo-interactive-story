/** 从候选里随机取一条，取不到返回 undefined */
export function pickNarration(pool: string[] | undefined): string | undefined {
  if (!pool?.length) return undefined;
  return pool[Math.floor(Math.random() * pool.length)];
}

/** 结局模板插值 */
export function fillEpilogue(template: string, integrity: number): string {
  return template.replace('{integrity}', String(integrity));
}
